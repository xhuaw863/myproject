    /** 获取某天对应的节气名称(当天恰为节气日返回名称, 否则 null) */
    public String getSolarTerm(LocalDate date) {
        if (date == null) {
            return null;
        }
        int[][] table = tableOf(date.getYear());
        for (int i = 0; i < SOLAR_TERMS.length; i++) {
            if (table[i][0] == date.getMonthValue() && table[i][1] == date.getDayOfMonth()) {
                return SOLAR_TERMS[i];
            }
        }
        return null;
    }

    /**
     * 获取日期范围内的所有节气(升序 LinkedHashMap: 节气日 → 节气名)。
     * 跨度上限 800 天(体温单场景 7 天/窗口, 上限仅防御异常入参); start 晚于 end 时返回空 Map。
     */
    public Map<LocalDate, String> getSolarTermsInRange(LocalDate start, LocalDate end) {
        Map<LocalDate, String> out = new LinkedHashMap<>();
        if (start == null || end == null || start.isAfter(end)) {
            return out;
        }
        LocalDate e = end;
        if (start.plusDays(800).isBefore(e)) {
            e = start.plusDays(800);
        }
        for (LocalDate d = start; !d.isAfter(e); d = d.plusDays(1)) {
            String term = getSolarTerm(d);
            if (term != null) {
                out.put(d, term);
            }
        }
        return out;
    }

    /** 年份取表: 查表范围内直接命中; 范围外按最近基准年外推(公历节气日期年际漂移<±1天) */
    private static int[][] tableOf(int year) {
        int[][] table = TERM_TABLE.get(year);
        if (table != null) {
            return table;
        }
        int base = Math.max(BASE_YEAR_MIN, Math.min(BASE_YEAR_MAX, year));
        return TERM_TABLE.get(base);
    }
